<p>This policy explains what personal information {{ $identity['name'] }} collects, why, and what you can ask us to do with it.</p>

<h2>What we collect</h2>
<ul>
    <li><strong>Account details:</strong> your name, mobile number, email address and password (stored only in scrambled, unreadable form).</li>
    <li><strong>Order details:</strong> delivery addresses, the items you buy, payment method and, for bKash or Nagad, the transaction ID you enter.</li>
    <li><strong>Business documents:</strong> for wholesale buyers and sellers, trade licence and related business details.</li>
    <li><strong>Technical data:</strong> a session cookie that keeps you signed in and remembers your cart.</li>
</ul>

<h2>Why we use it</h2>
<ul>
    <li>To deliver your orders and keep you updated by SMS.</li>
    <li>To send one-time codes that confirm your mobile number and protect your account.</li>
    <li>To check payments, prevent fraud and settle returns.</li>
    <li>To approve wholesale and seller accounts.</li>
</ul>

<h2>Who we share it with</h2>
<ul>
    <li><strong>The seller</strong> of the items you order, so they can prepare and send your parcel.</li>
    <li><strong>The delivery company</strong>, which receives your name, phone number and address.</li>
    <li><strong>Our SMS provider</strong>, which receives your mobile number to deliver messages and codes.</li>
    <li>Government authorities, only when the law requires it.</li>
</ul>
<p>We do not sell your personal information.</p>

<h2>How long we keep it</h2>
<p>We keep order and payment records for as long as the law requires for accounting and tax. You can ask us to close your account; we will then remove what we are not required to keep.</p>

<h2>Your choices</h2>
<p>You can update your addresses in your account at any time. To get a copy of your information, correct it, or close your account, <a href="{{ route('pages.contact') }}">contact us</a>.</p>
